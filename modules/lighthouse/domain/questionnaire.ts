export type PillarId = "E" | "S" | "G";

export type LikertOption = {
  label: string;
  value: 1 | 2 | 3 | 4 | 5;
};

export type LighthouseQuestion = {
  id: string;
  text: string;
  options: LikertOption[];
};

export type LighthouseKpi = {
  id: string;
  label: string;
  pillar: PillarId;
  pillarLabel: string;
  questions: [LighthouseQuestion, LighthouseQuestion];
};

function opts(labels: [string, string, string, string, string]): LikertOption[] {
  return labels.map((label, i) => ({
    label,
    value: (5 - i) as 1 | 2 | 3 | 4 | 5,
  }));
}

