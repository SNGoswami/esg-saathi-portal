export const TOTAL_QUESTIONS = LIGHTHOUSE_KPIS.length * 2;

export function countAnswered(answers: Record<string, number>): number {
  return LIGHTHOUSE_KPIS.reduce((n, kpi) => {
    const q1 = answers[kpi.questions[0].id];
    const q2 = answers[kpi.questions[1].id];
    return n + (q1 != null ? 1 : 0) + (q2 != null ? 1 : 0);
  }, 0);
}

const QUESTIONS_PER_PILLAR = 6;

export function countAnsweredByPillar(
  answers: Record<string, number>,
): Record<PillarId, { answered: number; total: number }> {
  const out: Record<PillarId, { answered: number; total: number }> = {
    E: { answered: 0, total: QUESTIONS_PER_PILLAR },
    S: { answered: 0, total: QUESTIONS_PER_PILLAR },
    G: { answered: 0, total: QUESTIONS_PER_PILLAR },
  };
  for (const kpi of LIGHTHOUSE_KPIS) {
    const q1 = answers[kpi.questions[0].id];
    const q2 = answers[kpi.questions[1].id];
    if (q1 != null) out[kpi.pillar].answered += 1;
    if (q2 != null) out[kpi.pillar].answered += 1;
  }
  return out;
}
